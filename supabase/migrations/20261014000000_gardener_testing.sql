create table if not exists public.projects (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  name text not null check (char_length(name) between 1 and 80),
  description text not null check (char_length(description) between 1 and 300),
  next_step text,
  archive_reason text,
  details jsonb not null default '{"todos":[],"projectType":"ongoing","inFloat":false,"context":"","position":null,"matrixPosition":null,"quadrant":"plan"}'::jsonb,
  deadline date,
  status text not null default 'active' check (status in ('active','completed','archived')),
  plant_variant integer not null default 0 check (plant_variant between 0 and 5),
  demo_key text,
  created_at timestamptz not null default now(),
  completed_at timestamptz,
  unique (id, user_id),
  unique (user_id, demo_key)
);

create table if not exists public.efforts (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  project_id bigint not null,
  text text not null check (char_length(text) between 1 and 240),
  created_at timestamptz not null default now(),
  foreign key (project_id, user_id) references public.projects(id, user_id) on delete cascade
);

create table if not exists public.outcomes (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  project_id bigint not null,
  type text not null check (char_length(type) between 1 and 40),
  value text not null check (char_length(value) between 1 and 80),
  note text check (char_length(note) <= 200),
  created_at timestamptz not null default now(),
  foreign key (project_id, user_id) references public.projects(id, user_id) on delete cascade
);

alter table public.projects enable row level security;
alter table public.efforts enable row level security;
alter table public.outcomes enable row level security;

grant select, insert, update, delete on public.projects, public.efforts, public.outcomes to authenticated;
grant usage, select on all sequences in schema public to authenticated;

create policy "projects_select_own" on public.projects for select to authenticated using (user_id = auth.uid());
create policy "projects_insert_own" on public.projects for insert to authenticated with check (user_id = auth.uid());
create policy "projects_update_own" on public.projects for update to authenticated using (user_id = auth.uid()) with check (user_id = auth.uid());
create policy "projects_delete_own" on public.projects for delete to authenticated using (user_id = auth.uid());
create policy "efforts_select_own" on public.efforts for select to authenticated using (user_id = auth.uid());
create policy "efforts_insert_own" on public.efforts for insert to authenticated with check (user_id = auth.uid());
create policy "efforts_delete_own" on public.efforts for delete to authenticated using (user_id = auth.uid());
create policy "outcomes_select_own" on public.outcomes for select to authenticated using (user_id = auth.uid());
create policy "outcomes_insert_own" on public.outcomes for insert to authenticated with check (user_id = auth.uid());
create policy "outcomes_delete_own" on public.outcomes for delete to authenticated using (user_id = auth.uid());

create or replace function public.garden_update_project(p_project_id bigint, p_details jsonb, p_effort text default null)
returns void language plpgsql security invoker set search_path = public as $$
declare changed bigint;
begin
  update public.projects set details = p_details, next_step = null
  where id = p_project_id and user_id = auth.uid() and status <> 'archived';
  get diagnostics changed = row_count;
  if changed <> 1 then raise exception 'Project not found or archived.'; end if;
  if p_effort is not null then
    insert into public.efforts(user_id, project_id, text) values (auth.uid(), p_project_id, p_effort);
  end if;
end;
$$;

create or replace function public.delete_garden_account(p_confirmation text)
returns void language plpgsql security definer set search_path = public, auth as $$
declare account_id uuid := auth.uid();
begin
  if p_confirmation <> 'DELETE' or account_id is null then raise exception 'Invalid deletion request.'; end if;
  delete from auth.users where id = account_id;
end;
$$;

revoke all on function public.garden_update_project(bigint, jsonb, text) from public;
grant execute on function public.garden_update_project(bigint, jsonb, text) to authenticated;
revoke all on function public.delete_garden_account(text) from public;
grant execute on function public.delete_garden_account(text) to authenticated;
